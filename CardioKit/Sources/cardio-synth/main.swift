// cardio-synth: writes the synthetic validation scenarios as session folders in the same format
// as real recordings, plus a ground-truth file. Output is SYNTHETIC and labelled as such.
//
// Usage: swift run cardio-synth <output-directory>

import CardioCore
import Foundation
import Storage
import SyntheticData

let args = CommandLine.arguments
guard args.count == 2 else {
    FileHandle.standardError.write(Data("usage: cardio-synth <output-directory>\n".utf8))
    exit(2)
}
let root = URL(fileURLWithPath: args[1], isDirectory: true)
let store = SessionStore(root: root)
let created = ISO8601DateFormatter().date(from: "2026-01-01T00:00:00Z")!

for scenario in SyntheticScenario.allCases {
    let rec = scenario.generate()
    let id = "SYNTHETIC-\(scenario.rawValue)"
    let accel = rec.accelerometer
    let reference = rec.config.startUptimeS
    let meta = SessionMetadata(
        id: id, isSynthetic: true,
        syntheticDescription: "SYNTHETIC DATA generated by cardio-synth (CardioKit/SyntheticData), scenario '\(scenario.rawValue)': \(scenario.summary) Not a measurement.",
        createdAt: created, label: "SYNTHETIC \(scenario.rawValue)",
        requestedDurationS: rec.config.durationS, recordedDurationS: rec.config.durationS,
        endReason: .completed, referenceUptimeS: reference, requestedMotionRateHz: rec.config.sampleRateHz,
        accelerometer: .summarize(accel), gyroscope: nil, audio: nil,
        device: DeviceInfo(modelIdentifier: "synthetic", systemName: "synthetic", systemVersion: "-"),
        appVersion: "cardio-synth", notes: ["Synthetic accelerometer only; no gyroscope or audio."])
    try store.finalize(metadata: meta, accelerometer: accel, gyroscope: nil)

    var truth = "beat_index,t_rel_s,t_uptime_s\n"
    for (i, t) in rec.beatTimes.enumerated() {
        truth += String(format: "%d,%.6f,%.6f\n", i, t - reference, t)
    }
    try Data(truth.utf8).write(to: store.directory(for: id).appendingPathComponent("truth_beats.csv"))
    print("wrote \(id): \(accel.samples.count) samples, \(rec.beatTimes.count) true beats")
}
